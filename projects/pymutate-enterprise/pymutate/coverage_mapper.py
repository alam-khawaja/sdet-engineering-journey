"""Maps ``(rel_path, lineno)`` to the exact pytest node IDs that execute that line.

The test suite runs once under ``<target-python> -m coverage run -m pytest``
with a tiny throwaway pytest plugin (written to a temp dir and put on
``PYTHONPATH``) that calls ``Coverage.switch_context(item.nodeid)`` around
every test. Each measured line in the ``.coverage`` SQLite database is then
tagged with the node IDs of the tests that ran it, so each mutant only
re-runs the tests that can possibly kill it. ``pymutate`` itself never needs
to be installed in the target environment, only ``pytest`` and ``coverage``.

The run forces ``COVERAGE_CORE=ctrace``: the ``sys.monitoring`` core (default on
Python 3.14+) stops reporting a line after its first execution, so every test
after the first would silently drop out of the map.

Lines executed only at import time (``def`` lines, default argument values,
module constants) carry the empty context. They fall back to every test that
covers any other line of the same file, because those tests import the module.
"""

from __future__ import annotations

import os
import subprocess
import time
from collections.abc import Iterable
from dataclasses import dataclass, field
from pathlib import Path

from coverage import CoverageData

PLUGIN_MODULE = "pymutate_context_plugin"

PLUGIN_SOURCE = '''"""Generated by pymutate: tag coverage contexts with exact pytest node IDs."""
import coverage
import pytest


@pytest.hookimpl(hookwrapper=True)
def pytest_runtest_protocol(item, nextitem):
    cov = coverage.Coverage.current()
    if cov is not None:
        cov.switch_context(item.nodeid)
    try:
        yield
    finally:
        if cov is not None:
            cov.switch_context("")
'''

RCFILE_SOURCE = "[run]\nbranch = False\nparallel = False\n"


class CoverageMappingError(RuntimeError):
    """The instrumented test run failed or produced no usable data."""


@dataclass
class CoverageMap:
    project_root: Path
    line_tests: dict[tuple[str, int], tuple[str, ...]] = field(default_factory=dict)
    import_time_lines: dict[str, frozenset[int]] = field(default_factory=dict)
    duration_sec: float = 0.0

    def file_tests(self, rel_path: str) -> tuple[str, ...]:
        tests = {test for (path, _), node_ids in self.line_tests.items() if path == rel_path for test in node_ids}
        return tuple(sorted(tests))

    def covered_lines(self, rel_path: str) -> frozenset[int]:
        lines = {line for (path, line) in self.line_tests if path == rel_path}
        return frozenset(lines | set(self.import_time_lines.get(rel_path, frozenset())))

    def tests_for(self, rel_path: str, lines: Iterable[int]) -> tuple[str, ...]:
        found: set[str] = set()
        needs_file_fallback = False
        import_lines = self.import_time_lines.get(rel_path, frozenset())
        for line in lines:
            node_ids = self.line_tests.get((rel_path, line))
            if node_ids:
                found.update(node_ids)
            elif line in import_lines:
                needs_file_fallback = True
        if not found and needs_file_fallback:
            found.update(self.file_tests(rel_path))
        return tuple(sorted(found))

    @property
    def all_tests(self) -> tuple[str, ...]:
        return tuple(sorted({test for node_ids in self.line_tests.values() for test in node_ids}))


def _rel_posix(path: str, project_root: Path) -> str | None:
    try:
        return Path(path).resolve().relative_to(project_root.resolve()).as_posix()
    except ValueError:
        return None


def read_coverage_data(data_file: Path, project_root: Path) -> CoverageMap:
    """Build a :class:`CoverageMap` from a ``.coverage`` SQLite file with per-test contexts."""
    if not data_file.is_file():
        raise CoverageMappingError(f"Coverage data file {data_file} was not created")
    data = CoverageData(basename=str(data_file))
    data.read()

    line_tests: dict[tuple[str, int], set[str]] = {}
    import_time: dict[str, set[int]] = {}
    for measured in data.measured_files():
        rel_path = _rel_posix(measured, project_root)
        if rel_path is None:
            continue
        contexts_by_line = data.contexts_by_lineno(measured)
        for lineno, contexts in contexts_by_line.items():
            node_ids = {context for context in contexts if context}
            if node_ids:
                line_tests.setdefault((rel_path, lineno), set()).update(node_ids)
            else:
                import_time.setdefault(rel_path, set()).add(lineno)

    return CoverageMap(
        project_root=project_root,
        line_tests={key: tuple(sorted(value)) for key, value in line_tests.items()},
        import_time_lines={key: frozenset(value) for key, value in import_time.items()},
    )


def include_patterns(project_root: Path, source_paths: Iterable[str]) -> list[str]:
    """``--include`` globs for files and directories (``--source`` rejects single files)."""
    patterns: list[str] = []
    for entry in source_paths:
        target = (project_root / entry).resolve()
        if target.is_dir():
            patterns.extend([f"{target.as_posix()}/*", f"{target.as_posix()}/**/*"])
        else:
            patterns.append(target.as_posix())
    return patterns


def build_coverage_map(
    *,
    project_root: Path,
    target_python: str,
    source_paths: Iterable[str],
    test_paths: Iterable[str],
    work_dir: Path,
    timeout_sec: float = 600.0,
) -> CoverageMap:
    """Run the suite once under coverage with per-test contexts and parse the result."""
    work_dir.mkdir(parents=True, exist_ok=True)
    plugin_dir = work_dir / "coverage_plugin"
    plugin_dir.mkdir(exist_ok=True)
    (plugin_dir / f"{PLUGIN_MODULE}.py").write_text(PLUGIN_SOURCE, encoding="utf-8")
    rcfile = work_dir / "coveragerc"
    rcfile.write_text(RCFILE_SOURCE, encoding="utf-8")
    data_file = work_dir / ".coverage"
    if data_file.exists():
        data_file.unlink()

    include = ",".join(include_patterns(project_root, source_paths))
    command = [
        target_python,
        "-m",
        "coverage",
        "run",
        f"--rcfile={rcfile}",
        f"--data-file={data_file}",
        f"--include={include}",
        "-m",
        "pytest",
        "-q",
        "--tb=short",
        "-p",
        "no:cacheprovider",
        "-p",
        PLUGIN_MODULE,
        *test_paths,
    ]
    env = os.environ.copy()
    env["PYTHONPATH"] = os.pathsep.join(
        part for part in (str(plugin_dir), env.get("PYTHONPATH", "")) if part
    )
    env["PYTHONDONTWRITEBYTECODE"] = "1"
    env["COVERAGE_CORE"] = "ctrace"

    started = time.perf_counter()
    try:
        completed = subprocess.run(
            command,
            cwd=project_root,
            env=env,
            capture_output=True,
            text=True,
            timeout=timeout_sec,
            check=False,
        )
    except subprocess.TimeoutExpired as exc:
        raise CoverageMappingError(f"Coverage run exceeded {timeout_sec:.0f}s") from exc
    except FileNotFoundError as exc:
        raise CoverageMappingError(f"Target python not found: {target_python}") from exc
    duration = time.perf_counter() - started

    if completed.returncode != 0:
        tail = (completed.stdout + completed.stderr)[-3000:]
        raise CoverageMappingError(
            f"Instrumented test run failed with exit code {completed.returncode}. "
            f"Is 'coverage' installed for {target_python}?\n{tail}"
        )

    coverage_map = read_coverage_data(data_file, project_root)
    coverage_map.duration_sec = duration
    if not coverage_map.line_tests:
        raise CoverageMappingError(
            "Coverage data has no per-test contexts; no source line was executed by any test"
        )
    return coverage_map
